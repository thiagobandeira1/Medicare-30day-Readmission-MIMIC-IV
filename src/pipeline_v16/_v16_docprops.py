# -*- coding: utf-8 -*-
"""Replace the python-docx template document properties (author "python-docx",
comment "generated by python-docx", dates from 2013) with the paper's own, in
place. Text and formatting are not touched.

usage: py _v16_docprops.py <docx> [<docx> ...]"""
import sys
from datetime import datetime, timezone
from pathlib import Path
from docx import Document

TITLE = ("Future-Information Leakage in 30-Day Readmission Prediction: An "
         "Empirical Audit and a Calibrated Electronic Health Record Model in "
         "Medicare-Insured Adults")
now = datetime.now(timezone.utc).replace(microsecond=0, tzinfo=None)
for f in sys.argv[1:]:
    p = Path(f)
    d = Document(str(p))
    cp = d.core_properties
    cp.author = "Thiago Bandeira"
    cp.last_modified_by = "Thiago Bandeira"
    cp.title = p.stem.replace(" v16", "")
    cp.subject = TITLE
    cp.keywords = ("Patient Readmission; Medicare; Machine Learning; Electronic "
                   "Health Records; Healthcare Disparities")
    cp.comments = ""
    cp.category = ""
    cp.created = now
    cp.modified = now
    cp.revision = 1
    d.save(str(p))
    print("properties set:", p.name)
